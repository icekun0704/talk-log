import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const built = resolve(root, "dist/app.html");

if (!existsSync(built)) {
  console.error("dist/app.html が見つかりません。先に vite build を実行してください。");
  process.exit(1);
}

const banner = "<!-- Generated by `npm run build` from src/. Do not edit this file directly. -->\n";
// Normalize line endings so Windows and Linux builds are byte-identical.
const html = readFileSync(built, "utf8").replace(/\r\n/g, "\n");

if (!html.startsWith("<!doctype html>")) {
  console.error("ビルド結果がHTMLではありません。");
  process.exit(1);
}

const output = banner + html;

// 1. GitHub Pages serves the repository root, so `index.html` is the built app.
writeFileSync(resolve(root, "index.html"), output);
// 2. Keep the historical standalone filename working.
writeFileSync(resolve(root, "line_chat_analyzer_web.html"), output);
// 3. Also place an index.html in dist for Actions-based Pages deployments.
writeFileSync(resolve(root, "dist/index.html"), output);

// Make sure the output really is self-contained.
if (/<script[^>]+src="\/|href="\/assets\//.test(output)) {
  console.error("外部アセット参照が残っています。単一HTMLになっていません。");
  process.exit(1);
}

const kb = Math.round((Buffer.byteLength(output) / 1024) * 10) / 10;
console.log(`単一HTMLを生成しました（${kb} kB）: index.html / line_chat_analyzer_web.html`);
